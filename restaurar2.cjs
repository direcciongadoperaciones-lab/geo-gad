writeLines("src/App.tsx", [
  'import React, { useState, useEffect, useRef } from "react";',
  'import { UsuarioGad, BaseGad, RegistroEstadistico } from "./types";',
  'import { BASES_FIJAS } from "./services/data";',
  'import { Login } from "./components/Login";',
  'import { BaseDashboard } from "./components/BaseDashboard";',
  'import { SuperAdminDashboard } from "./components/SuperAdminDashboard";',
  'import { PwaInstallBanner } from "./components/PwaInstallBanner";',
  'import { db } from "./services/firebase";',
  'import { collection, doc, onSnapshot, setDoc } from "firebase/firestore";',
  'import { dispararAlertaSonoraYvibracion } from "./services/whatsapp";',
  '',
  'export function App() {',
  '  const [usuario, setUsuario] = useState<UsuarioGad | null>(() => {',
  '    const s = localStorage.getItem("geo_gad_sesion");',
  '    return s ? JSON.parse(s) : null;',
  '  });',
  '',
  '  const [bases, setBases] = useState<BaseGad[]>(() => {',
  '    const s = localStorage.getItem("geo_gad_bases_v3");',
  '    if (s) {',
  '      try {',
  '        const parsed: BaseGad[] = JSON.parse(s);',
  '        if (parsed.length === 45 && parsed[0].coordinacion) return parsed;',
  '      } catch (e) {}',
  '    }',
  '    return BASES_FIJAS;',
  '  });',
  '',
  '  const [historial, setHistorial] = useState<RegistroEstadistico[]>(() => {',
  '    const s = localStorage.getItem("geo_gad_historial_mes");',
  '    return s ? JSON.parse(s) : [];',
  '  });',
  '',
  '  const prevEstadosRef = useRef<Record<number, string>>({});',
  '',
  '  // Actualizacion silenciosa de Service Worker cada 60 segundos en todos los celulares',
  '  useEffect(() => {',
  '    if ("serviceWorker" in navigator) {',
  '      const swTimer = setInterval(() => {',
  '        navigator.serviceWorker.getRegistration().then(reg => {',
  '          if (reg) reg.update().catch(() => {});',
  '        });',
  '      }, 60000);',
  '      return () => clearInterval(swTimer);',
  '    }',
  '  }, []);',
  '',
  '  useEffect(() => {',
  '    localStorage.setItem("geo_gad_bases_v3", JSON.stringify(bases));',
  '  }, [bases]);',
  '',
  '  useEffect(() => {',
  '    localStorage.setItem("geo_gad_historial_mes", JSON.stringify(historial));',
  '  }, [historial]);',
  '',
  '  useEffect(() => {',
  '    const onStorage = (e: StorageEvent) => {',
  '      if (e.key === "geo_gad_bases_v3" && e.newValue) {',
  '        setBases(JSON.parse(e.newValue));',
  '      }',
  '    };',
  '    window.addEventListener("storage", onStorage);',
  '',
  '    let unsubFirestore: (() => void) | null = null;',
  '    const apiKey = import.meta.env.VITE_FIREBASE_API_KEY;',
  '    if (apiKey && !apiKey.includes("Mock") && !apiKey.includes("tu_api_key")) {',
  '      try {',
  '        unsubFirestore = onSnapshot(collection(db, "serviciosActivos"), snap => {',
  '          const cambios: Record<number, BaseGad> = {};',
  '          snap.forEach(d => {',
  '            const data = d.data() as BaseGad;',
  '            if (data && data.id) {',
  '              cambios[data.id] = data;',
  '              const prev = prevEstadosRef.current[data.id];',
  '              if (prev && prev !== data.estado && data.estado === "ROJO") {',
  '                dispararAlertaSonoraYvibracion();',
  '              }',
  '              prevEstadosRef.current[data.id] = data.estado;',
  '            }',
  '          });',
  '          if (Object.keys(cambios).length > 0) {',
  '            setBases(prev => prev.map(b => cambios[b.id] ? { ...b, ...cambios[b.id] } : b));',
  '          }',
  '        });',
  '      } catch (e) {}',
  '    }',
  '',
  '    return () => {',
  '      window.removeEventListener("storage", onStorage);',
  '      if (unsubFirestore) unsubFirestore();',
  '    };',
  '  }, []);',
  '',
  '  const handleUpdateBase = (b: BaseGad, registrarEstadistica = false) => {',
  '    let esViaje = false;',
  '    if (!b.esConurbano && b.estado !== "VERDE") {',
  '      const gpsEnConu = b.lat >= -35.3 && b.lat <= -34.0 && b.lng >= -59.5 && b.lng <= -57.8;',
  '      const lugarTxt = (b.lugar || "").toLowerCase();',
  '      const kws = ["la matanza", "matanza", "moron", "quilmes", "lanus", "lomas", "caba", "san martin", "tres de febrero", "cintura", "conurbano"];',
  '      if (gpsEnConu || kws.some(k => lugarTxt.includes(k))) esViaje = true;',
  '    }',
  '    const actualizada: BaseGad = { ...b, esViajeIntConu: esViaje };',
  '    setBases(prev => prev.map(item => item.id === actualizada.id ? actualizada : item));',
  '',
  '    if (registrarEstadistica) {',
  '      const nuevoReg: RegistroEstadistico = {',
  '        id: "reg_" + Date.now(),',
  '        fecha: new Date().toLocaleDateString("es-AR"),',
  '        base: actualizada.nombre,',
  '        dgado: actualizada.dgado || "",',
  '        servicio: actualizada.servicio || "",',
  '        lugar: actualizada.lugar || "",',
  '        horario: actualizada.horarioInicio || "",',
  '        aCargo: actualizada.aCargo || "",',
  '        telefono: actualizada.telefono || "",',
  '        estado: actualizada.estado,',
  '        viaje: esViaje ? "SI" : "NO",',
  '        puntosRojo: actualizada.puntosRojo,',
  '        puntosAmarillo: actualizada.puntosAmarillo,',
  '        lat: actualizada.lat,',
  '        lng: actualizada.lng',
  '      };',
  '      setHistorial(prev => [...prev, nuevoReg]);',
  '    }',
  '',
  '    const apiKey = import.meta.env.VITE_FIREBASE_API_KEY;',
  '    if (apiKey && !apiKey.includes("Mock") && !apiKey.includes("tu_api_key")) {',
  '      setDoc(doc(db, "serviciosActivos", "base_" + actualizada.id), actualizada).catch(() => {});',
  '    }',
  '  };',
  '',
  '  return (',
  '    <>',
  '      {!usuario ? (',
  '        <Login onLogin={u => { setUsuario(u); localStorage.setItem("geo_gad_sesion", JSON.stringify(u)); }} />',
  '      ) : usuario.rol === "base" ? (',
  '        <BaseDashboard usuario={usuario} bases={bases} onUpdateBase={handleUpdateBase} onLogout={() => { setUsuario(null); localStorage.removeItem("geo_gad_sesion"); }} />',
  '      ) : (',
  '        <SuperAdminDashboard',
  '          usuario={usuario}',
  '          bases={bases}',
  '          historial={historial}',
  '          onUpdateBases={setBases}',
  '          onClearHistorial={() => setHistorial([])}',
  '          onLogout={() => { setUsuario(null); localStorage.removeItem("geo_gad_sesion"); }}',
  '        />',
  '      )}',
  '      <PwaInstallBanner />',
  '    </>',
  '  );',
  '}',
  'export default App;'
]);

